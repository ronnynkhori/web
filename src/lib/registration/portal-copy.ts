export type PortalCopy = typeof en;

export function portalCopy(locale: Locale): PortalCopy {
  return locale === "pt" ? pt : en;
}

export function fillCopy(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}
